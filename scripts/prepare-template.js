import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const distHtmlPath = path.join(__dirname, '../dist/index.html');
const outputJsPath = path.join(__dirname, '../api/_html_template.js');
const metadataJsonPath = path.join(__dirname, '../api/_route_metadata.json');

if (!fs.existsSync(distHtmlPath)) {
  console.error('[Template] Error: dist/index.html does not exist. Run vite build first.');
  process.exit(1);
}

const html = fs.readFileSync(distHtmlPath, 'utf-8');
const metadata = fs.existsSync(metadataJsonPath) 
  ? JSON.parse(fs.readFileSync(metadataJsonPath, 'utf8'))
  : {};

const fileContent = `// Auto-generated by scripts/prepare-template.js at build time. Do not edit manually.\nexport const indexHtml = ${JSON.stringify(html)};\n\nexport const routeMetadata = ${JSON.stringify(metadata)};\n`;

fs.writeFileSync(outputJsPath, fileContent, 'utf-8');
console.log(`[Template] Successfully generated api/_html_template.js (${Buffer.byteLength(fileContent)} bytes) from dist/index.html with ${Object.keys(metadata).length} route metadata entries.`);
